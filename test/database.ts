import 'dotenv/config';
import { randomUUID } from 'node:crypto';
import { DataSource, DataSourceOptions } from 'typeorm';

export async function createTestDatabase() {
  if (!process.env.DATABASE_URL) throw new Error('DATABASE_URL is required for PostgreSQL integration tests');
  const schema = `rfq_test_${randomUUID().replace(/-/g, '')}`;
  const admin = new DataSource({ type: 'postgres', url: process.env.DATABASE_URL });
  await admin.initialize();
  await admin.query(`CREATE SCHEMA "${schema}"`);
  return {
    options: {
      type: 'postgres', url: process.env.DATABASE_URL, schema,
      synchronize: true, autoLoadEntities: true,
    } as DataSourceOptions & { autoLoadEntities: boolean },
    async cleanup() {
      // This schema is generated by this test run, never an existing application schema.
      await admin.query(`DROP SCHEMA "${schema}" CASCADE`);
      await admin.destroy();
    },
  };
}
